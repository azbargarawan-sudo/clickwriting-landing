// Generates the final paper (Word document, Hebrew, RTL, double spacing).
// Run: node papers/build-paper.js   (requires the `docx` npm package)
const fs = require("fs");
const path = require("path");
const {
  Document, Packer, Paragraph, TextRun, AlignmentType, HeadingLevel,
  Header, Footer, PageNumber, PageBreak, TabStopType,
} = require("docx");

const FONT = { ascii: "David", hAnsi: "David", cs: "David", eastAsia: "David" };
const BODY_SIZE = 24; // 12pt
const HEAD_SIZE = 28; // 14pt
const TITLE_SIZE = 32; // 16pt

function run(text, opts = {}) {
  return new TextRun({
    text,
    font: FONT,
    rightToLeft: true,
    size: opts.size || BODY_SIZE,
    sizeComplexScript: opts.size || BODY_SIZE,
    bold: !!opts.bold,
    boldComplexScript: !!opts.bold,
    italics: !!opts.italics,
    italicsComplexScript: !!opts.italics,
    underline: opts.underline ? {} : undefined,
  });
}

// A body paragraph. `parts` is a string or an array of strings / {text, bold}.
function para(parts, opts = {}) {
  const runs = (Array.isArray(parts) ? parts : [parts]).map((p) =>
    typeof p === "string" ? run(p, opts) : run(p.text, { ...opts, ...p })
  );
  return new Paragraph({
    children: runs,
    bidirectional: true,
    alignment: opts.align || AlignmentType.JUSTIFIED,
    spacing: { line: 480, lineRule: "auto", after: opts.after ?? 0, before: opts.before ?? 0 },
    indent: opts.noIndent ? undefined : { firstLine: 567 },
  });
}

function heading(text, level = HeadingLevel.HEADING_1) {
  return new Paragraph({
    children: [run(text, { bold: true, size: level === HeadingLevel.HEADING_1 ? HEAD_SIZE : BODY_SIZE })],
    heading: level,
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { line: 480, lineRule: "auto", before: 240, after: 0 },
  });
}

function centered(text, opts = {}) {
  return new Paragraph({
    children: [run(text, opts)],
    bidirectional: true,
    alignment: AlignmentType.CENTER,
    spacing: { line: 480, lineRule: "auto", after: opts.after ?? 0 },
  });
}

function bib(text) {
  return new Paragraph({
    children: [run(text)],
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { line: 360, lineRule: "auto", after: 120 },
    indent: { left: 567, hanging: 567 },
  });
}

