// Generates the final paper (Word document, Hebrew, RTL).
// Formatting: David 12, line spacing 1.5, justified, 2.54 cm margins, A4.
// Run: node papers/build-paper.js   (requires the `docx` npm package)
const fs = require("fs");
const path = require("path");
const {
  Document, Packer, Paragraph, TextRun, AlignmentType, HeadingLevel,
  Header, Footer, PageNumber, PageBreak,
} = require("docx");

const FONT = { ascii: "David", hAnsi: "David", cs: "David", eastAsia: "David" };
const BODY_SIZE = 24;  // 12pt
const HEAD_SIZE = 28;  // 14pt
const TITLE_SIZE = 32; // 16pt
const LINE = 360;      // 1.5 line spacing
const HANGING = 709;   // 1.25 cm

function run(text, opts = {}) {
  return new TextRun({
    text,
    font: FONT,
    rightToLeft: true,
    size: opts.size || BODY_SIZE,
    sizeComplexScript: opts.size || BODY_SIZE,
    bold: !!opts.bold,
    boldComplexScript: !!opts.bold,
    italics: !!opts.italics,
    italicsComplexScript: !!opts.italics,
  });
}

// Body paragraph. `parts` is a string or an array of strings / {text, bold, italics}.
function para(parts, opts = {}) {
  const runs = (Array.isArray(parts) ? parts : [parts]).map((p) =>
    typeof p === "string" ? run(p, opts) : run(p.text, { ...opts, ...p })
  );
  return new Paragraph({
    children: runs,
    bidirectional: true,
    alignment: opts.align || AlignmentType.JUSTIFIED,
    spacing: { line: LINE, lineRule: "auto", after: opts.after ?? 0, before: opts.before ?? 0 },
    indent: opts.noIndent ? undefined : { firstLine: 567 },
  });
}

function heading(text) {
  return new Paragraph({
    children: [run(text, { bold: true, size: HEAD_SIZE })],
    heading: HeadingLevel.HEADING_1,
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { line: LINE, lineRule: "auto", before: 240, after: 120 },
  });
}

function centered(text, opts = {}) {
  return new Paragraph({
    children: [run(text, opts)],
    bidirectional: true,
    alignment: AlignmentType.CENTER,
    spacing: { line: LINE, lineRule: "auto", after: opts.after ?? 0 },
  });
}

function pageBreak() {
  return new Paragraph({ children: [new PageBreak()] });
}

// Reference-list entry: hanging indent, no numbering. `parts` allows italics for titles.
function ref(parts) {
  const runs = parts.map((p) => (typeof p === "string" ? run(p) : run(p.text, p)));
  return new Paragraph({
    children: runs,
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { line: LINE, lineRule: "auto", after: 120 },
    indent: { left: HANGING, hanging: HANGING },
  });
}

