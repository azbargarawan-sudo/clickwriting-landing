// ---- helpers ----------------------------------------------------------
// Split a Hebrew string so Latin/digit stretches get Times New Roman.
function runs(text, extra = {}) {
  const out = [];
  const re = /([A-Za-z][A-Za-z.'\-]*(?:\s+[A-Za-z][A-Za-z.'\-]*)*)/g;
  let last = 0, m;
  while ((m = re.exec(text)) !== null) {
    if (m.index > last) {
      out.push(new TextRun({ text: text.slice(last, m.index), font: HE, size: SZ, rightToLeft: true, ...extra }));
    }
    out.push(new TextRun({ text: m[0], font: EN, size: SZ, ...extra }));
    last = m.index + m[0].length;
  }
  if (last < text.length) {
    out.push(new TextRun({ text: text.slice(last), font: HE, size: SZ, rightToLeft: true, ...extra }));
  }
  return out;
}

// A space left at the end of a run, right before a differently-formatted run,
// gets swallowed by justified RTL layout. Carry it into the following run.
function normalize(parts) {
  const norm = parts.map((x) => (Array.isArray(x) ? [x[0], x[1] || {}] : [x, {}]));
  for (let i = 0; i < norm.length - 1; i++) {
    const m = norm[i][0].match(/ +$/);
    if (m) {
      norm[i][0] = norm[i][0].slice(0, -m[0].length);
      norm[i + 1][0] = m[0] + norm[i + 1][0];
    }
  }
  return norm;
}

// parts: array of strings, or [string, {italics:true}] pairs
function segs(parts, base = {}) {
  const out = [];
  for (const [text, opts] of normalize(parts)) out.push(...runs(text, { ...base, ...opts }));
  return out;
}

function p(parts, opts = {}) {
  return new Paragraph({
    bidirectional: true,
    alignment: opts.alignment || AlignmentType.JUSTIFIED,
    spacing: { line: LINE, after: opts.after === undefined ? 120 : opts.after, before: opts.before || 0 },
    children: Array.isArray(parts) ? segs(parts) : runs(parts),
  });
}

function h(text) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { line: LINE, before: 200, after: 80 },
    keepNext: true,
    children: runs(text, { bold: true }),
  });
}

// Reference-list entry: hanging indent, 1.5 spacing.
function ref(parts, english = false) {
  return new Paragraph({
    bidirectional: !english,
    alignment: english ? AlignmentType.LEFT : AlignmentType.RIGHT,
    spacing: { line: LINE, after: 120 },
    indent: english ? { left: HANG, hanging: HANG } : { right: HANG, hanging: HANG },
    children: english
      ? normalize(parts).map(([text, opts]) => new TextRun({ text, font: EN, size: SZ, ...opts }))
      : segs(parts),
  });
}

