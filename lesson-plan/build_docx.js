const {
  Document, Packer, Paragraph, TextRun, Table, TableRow, TableCell,
  WidthType, AlignmentType, ShadingType, PageOrientation, VerticalAlign, PageBreak,
} = require('docx');
const fs = require('fs');

const FONT = 'David';

function heRun(text, opts = {}) {
  return new TextRun({ text, rightToLeft: true, font: FONT, ...opts });
}
function hePara(text, opts = {}) {
  const { bold, size, underline, spacingAfter = 120, spacingBefore, alignment } = opts;
  return new Paragraph({
    bidirectional: true,
    alignment: alignment || AlignmentType.START,
    spacing: { after: spacingAfter, before: spacingBefore || 0 },
    children: [heRun(text, { bold, size, underline })],
  });
}
function title(text) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.CENTER,
    spacing: { after: 240 },
    children: [heRun(text, { bold: true, size: 36, underline: {} })],
  });
}
function sectionHead(text) {
  return new Paragraph({
    bidirectional: true,
    spacing: { before: 280, after: 120 },
    children: [heRun(text, { bold: true, size: 28, underline: {} })],
  });
}
function subHead(text) {
  return new Paragraph({
    bidirectional: true,
    spacing: { before: 200, after: 100 },
    children: [heRun(text, { bold: true, size: 24 })],
  });
}
function numbered(ref, text) {
  return new Paragraph({
    bidirectional: true,
    numbering: { reference: ref, level: 0 },
    spacing: { after: 80 },
    children: [heRun(text)],
  });
}
function pageBreakPara() {
  return new Paragraph({ children: [new PageBreak()] });
}
function cellParas(texts, opts = {}) {
  const arr = Array.isArray(texts) ? texts : [texts];
  return arr.map(t => new Paragraph({
    bidirectional: true,
    alignment: opts.center ? AlignmentType.CENTER : AlignmentType.START,
    spacing: { after: 40 },
    children: [heRun(t, { size: opts.size || 20, bold: opts.bold })],
  }));
}
function makeCell(texts, width, opts = {}) {
  return new TableCell({
    width: { size: width, type: WidthType.DXA },
    verticalAlign: VerticalAlign.CENTER,
    columnSpan: opts.span,
    shading: opts.shade ? { type: ShadingType.CLEAR, fill: opts.shade, color: 'auto' } : undefined,
    margins: { top: 60, bottom: 60, left: 90, right: 90 },
    children: cellParas(texts, opts),
  });
}

