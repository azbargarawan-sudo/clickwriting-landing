def esc(t):
    return t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')

def run_xml(text):
    return ('<w:r><w:rPr><w:rFonts w:hint="cs"/><w:rtl/></w:rPr>'
            f'<w:t xml:space="preserve">{esc(text)}</w:t></w:r>')

# ============ 1. background blanks (underscore runs) ============
def para_text(p):
    return ''.join(re.findall(r'<w:t[^>]*>([^<]*)</w:t>', p))

def fill_underscores(p, values):
    """Replace successive underscore sequences inside the paragraph's w:t with values."""
    out = p
    for v in values:
        m = re.search(r'(<w:t[^>]*>)([^<]*?)(_{3,})([^<]*)(</w:t>)', out)
        if not m:
            break
        out = out[:m.start()] + m.group(1) + m.group(2) + esc(v) + m.group(4) + m.group(5) + out[m.end():]
    # wipe any leftover underscore runs in this paragraph
    out = re.sub(r'(<w:t[^>]*>)([^<]*)(</w:t>)',
                 lambda mm: mm.group(1) + mm.group(2).replace('_', '') + mm.group(3), out)
    return out

