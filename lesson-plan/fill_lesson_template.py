def cell_para(text, bold=False):
    rpr = ('<w:rPr><w:rFonts w:ascii="Arial" w:hAnsi="Arial" w:cs="Arial" w:hint="cs"/>'
           + ('<w:b/><w:bCs/>' if bold else '')
           + '<w:sz w:val="20"/><w:szCs w:val="20"/><w:rtl/></w:rPr>')
    return ('<w:p><w:pPr><w:bidi/><w:spacing w:after="60" w:line="240" w:lineRule="auto"/>'
            '<w:rPr><w:sz w:val="20"/><w:szCs w:val="20"/><w:rtl/></w:rPr></w:pPr>'
            f'<w:r>{rpr}<w:t xml:space="preserve">{esc(text)}</w:t></w:r></w:p>')

def cell(texts, fill, bold_first=False):
    if isinstance(texts, str): texts = [texts]
    paras = ''.join(cell_para(t, bold=(bold_first and i == 0)) for i, t in enumerate(texts))
    if not paras: paras = cell_para('')
    return '<w:tc>' + TCPR.format(fill=fill) + paras + '</w:tc>'

def row(cells, fill):
    return ('<w:tr><w:trPr><w:trHeight w:val="484"/></w:trPr>'
            + ''.join(cell(c, fill, bold_first=(i == 0)) for i, c in enumerate(cells))
            + '</w:tr>')

