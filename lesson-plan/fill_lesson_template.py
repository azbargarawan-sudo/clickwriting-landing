def after_heading(heading, paras_xml):
    global doc
    m = re.search(r'<w:p [^>]*>(?:(?!</w:p>).)*?' + heading + r'.*?</w:p>', doc, re.S)
    p = m.group(0)
    doc = doc.replace(p, p + paras_xml, 1)

