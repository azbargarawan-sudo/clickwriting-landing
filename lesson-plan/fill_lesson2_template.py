    return (f'<w:p><w:pPr><w:bidi/><w:jc w:val="both"/><w:rPr><w:rtl/></w:rPr></w:pPr>'
            f'<w:r>{rpr}<w:t xml:space="preserve">{esc(text)}</w:t></w:r></w:p>')

