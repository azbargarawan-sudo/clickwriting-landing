const fs = require('fs');
const {
  Document, Packer, Paragraph, TextRun, AlignmentType, LineRuleType,
} = require('docx');

const FONT = { ascii: 'David', hAnsi: 'David', cs: 'David' };
const SIZE = 24; // 12pt in half-points

function run(text, opts = {}) {
  return new TextRun({
    text,
    font: FONT,
    size: SIZE,
    sizeComplexScript: SIZE,
    rightToLeft: true,
    bold: opts.bold || false,
    underline: opts.underline ? {} : undefined,
  });
}

// runs: string OR array of [text, opts]
function para(runs, opts = {}) {
  const children = (typeof runs === 'string' ? [[runs, {}]] : runs)
    .map(([t, o]) => run(t, { ...o, ...(opts.allBold ? { bold: true } : {}) }));
  return new Paragraph({
    children,
    bidirectional: true,
    alignment: opts.align || AlignmentType.JUSTIFIED,
    spacing: {
      line: 360, // 1.5 lines
      lineRule: LineRuleType.AUTO,
      before: opts.before ?? 0,
      after: opts.after ?? 0,
    },
  });
}

