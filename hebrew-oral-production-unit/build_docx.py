FONT = "David"

def set_rtl_para(p, align=WD_ALIGN_PARAGRAPH.JUSTIFY):
    pPr = p._p.get_or_add_pPr()
    if pPr.find(qn('w:bidi')) is None:
        bidi = OxmlElement('w:bidi')
        pPr.append(bidi)
    p.alignment = align

def style_run(r, size=12, bold=False, italic=False):
    r.font.name = FONT
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.italic = italic
    rPr = r._r.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    rFonts.set(qn('w:ascii'), FONT)
    rFonts.set(qn('w:hAnsi'), FONT)
    rFonts.set(qn('w:cs'), FONT)
    rtl = OxmlElement('w:rtl')
    rPr.append(rtl)
    szCs = OxmlElement('w:szCs')
    szCs.set(qn('w:val'), str(int(size * 2)))
    rPr.append(szCs)
    if bold:
        bCs = OxmlElement('w:bCs')
        rPr.append(bCs)

def para(doc, text, size=12, bold=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
         space_after=6, style=None, italic=False):
    p = doc.add_paragraph(style=style)
    set_rtl_para(p, align)
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    p.paragraph_format.space_after = Pt(space_after)
    r = p.add_run(text)
    style_run(r, size, bold, italic)
    return p

def heading(doc, text, level):
    # כותרות בסגנונות Heading 1-3 כדי שתוכן העניינים יזהה אותן
    p = doc.add_paragraph(style=f'Heading {level}')
    set_rtl_para(p, WD_ALIGN_PARAGRAPH.RIGHT)
    p.paragraph_format.space_before = Pt(12 if level == 1 else 8)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    sizes = {1: 16, 2: 14, 3: 12.5}
    r = p.add_run(text)
    style_run(r, sizes[level], bold=True)
    r.font.color.rgb = RGBColor(0, 0, 0)
    return p

def bullet(doc, text, size=12, bold=False):
    p = doc.add_paragraph(style='List Bullet')
    set_rtl_para(p, WD_ALIGN_PARAGRAPH.JUSTIFY)
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    p.paragraph_format.space_after = Pt(2)
    r = p.add_run(text)
    style_run(r, size, bold)
    return p

def page_break(doc):
    p = doc.add_paragraph()
    r = p.add_run()
    r.add_break(WD_BREAK.PAGE)

def rtl_table(doc, rows, header=True, col_widths=None, size=11):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    tblPr = t._tbl.tblPr
    bidi = OxmlElement('w:bidiVisual')
    tblPr.append(bidi)
    for i, row in enumerate(rows):
        for j, cell_text in enumerate(row):
            cell = t.cell(i, j)
            cell.paragraphs[0].text = ''
            p = cell.paragraphs[0]
            set_rtl_para(p, WD_ALIGN_PARAGRAPH.RIGHT)
            p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
            p.paragraph_format.space_after = Pt(2)
            r = p.add_run(cell_text)
            style_run(r, size, bold=(header and i == 0))
            if col_widths:
                cell.width = Cm(col_widths[j])
    return t

def add_toc(doc):
    p = doc.add_paragraph()
    set_rtl_para(p, WD_ALIGN_PARAGRAPH.RIGHT)
    fldBegin = OxmlElement('w:r')
    fc = OxmlElement('w:fldChar')
    fc.set(qn('w:fldCharType'), 'begin')
    fc.set(qn('w:dirty'), 'true')
    fldBegin.append(fc)
    p._p.append(fldBegin)
    rInstr = OxmlElement('w:r')
    instr = OxmlElement('w:instrText')
    instr.set(qn('xml:space'), 'preserve')
    instr.text = ' TOC \\o "1-3" \\h \\z \\u '
    rInstr.append(instr)
    p._p.append(rInstr)
    rSep = OxmlElement('w:r')
    fcSep = OxmlElement('w:fldChar')
    fcSep.set(qn('w:fldCharType'), 'separate')
    rSep.append(fcSep)
    p._p.append(rSep)
    rTxt = p.add_run('לעדכון תוכן העניינים: קליק ימני על שורה זו ובחירה ב"עדכן שדה"')
    style_run(rTxt, 11, italic=True)
    rEnd = OxmlElement('w:r')
    fcEnd = OxmlElement('w:fldChar')
    fcEnd.set(qn('w:fldCharType'), 'end')
    rEnd.append(fcEnd)
    p._p.append(rEnd)

def add_page_number_footer(doc):
    section = doc.sections[0]
    footer_p = section.footer.paragraphs[0]
    footer_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r1 = OxmlElement('w:r')
    fc1 = OxmlElement('w:fldChar'); fc1.set(qn('w:fldCharType'), 'begin')
    r1.append(fc1); footer_p._p.append(r1)
    r2 = OxmlElement('w:r')
    it = OxmlElement('w:instrText'); it.set(qn('xml:space'), 'preserve'); it.text = ' PAGE '
    r2.append(it); footer_p._p.append(r2)
    r3 = OxmlElement('w:r')
    fc3 = OxmlElement('w:fldChar'); fc3.set(qn('w:fldCharType'), 'end')
    r3.append(fc3); footer_p._p.append(r3)

