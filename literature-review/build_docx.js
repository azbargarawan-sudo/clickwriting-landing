// ---------- helpers ----------
const CM = 567; // twips per cm
const DOUBLE = { line: 480, lineRule: LineRuleType.AUTO };

function heRun(text, opts = {}) {
  return new TextRun({
    text,
    rightToLeft: true,
    font: { ascii: 'Times New Roman', hAnsi: 'Times New Roman', cs: 'David' },
    size: opts.size || 24,
    sizeComplexScript: opts.size || 24,
    bold: opts.bold || false,
    italics: opts.italics || false,
  });
}

function enRun(text, opts = {}) {
  return new TextRun({
    text,
    font: { ascii: 'Times New Roman', hAnsi: 'Times New Roman', cs: 'Times New Roman' },
    size: opts.size || 24,
    sizeComplexScript: opts.size || 24,
    bold: opts.bold || false,
    italics: opts.italics || false,
  });
}

// Hebrew body paragraph (RTL, justified-to-right, double spaced)
function hePara(text, opts = {}) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.START,
    spacing: { ...DOUBLE, after: opts.after ?? 0 },
    indent: opts.indent,
    children: [heRun(text, opts)],
    pageBreakBefore: opts.pageBreakBefore || false,
  });
}

// Chapter heading (RTL, bold, 14pt), starts on a new page
function heHeading(text, { newPage = true } = {}) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.START,
    spacing: { ...DOUBLE, after: 120 },
    pageBreakBefore: newPage,
    children: [heRun(text, { bold: true, size: 28 })],
  });
}

// Sub-heading (RTL, bold 12pt), same page
function heSub(text) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.START,
    spacing: { ...DOUBLE, before: 120 },
    children: [heRun(text, { bold: true, size: 24 })],
  });
}

// Centered cover line
function coverLine(text, { size = 24, bold = false, before = 0, after = 0 } = {}) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.CENTER,
    spacing: { line: 360, lineRule: LineRuleType.AUTO, before, after },
    children: [heRun(text, { size, bold })],
  });
}

// Hebrew reference entry: hanging indent 1.25cm, double spacing, RTL.
// parts: array of {t: text, i: italic}
function heRef(parts) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.START,
    spacing: DOUBLE,
    indent: { start: Math.round(1.25 * CM), hanging: Math.round(1.25 * CM) },
    children: parts.map(p => heRun(p.t, { italics: !!p.i })),
  });
}

// English reference entry: LTR, left aligned, hanging indent
function enRef(parts) {
  return new Paragraph({
    bidirectional: false,
    alignment: AlignmentType.LEFT,
    spacing: DOUBLE,
    indent: { left: Math.round(1.25 * CM), hanging: Math.round(1.25 * CM) },
    children: parts.map(p => enRun(p.t, { italics: !!p.i })),
  });
}

