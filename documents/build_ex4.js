const fs = require("fs");
const {
  Document, Packer, Paragraph, TextRun, AlignmentType, LineRuleType, PageNumber, Footer,
} = require("docx");

const FONT = "David";
const LINE = 480; // double spacing, as required in the assignment brief
const LANG = { value: "he-IL", bidirectional: "he-IL", eastAsia: "he-IL" };

function run(text, opts = {}) {
  return new TextRun({ text, font: FONT, size: 24, rightToLeft: true, noProof: true, language: LANG, ...opts });
}
function p(text, opts = {}) {
  const runs = Array.isArray(text) ? text : [run(text)];
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.JUSTIFIED,
    spacing: { line: LINE, lineRule: LineRuleType.AUTO, after: 0 },
    children: runs,
    ...opts,
  });
}
function q(text) {
  return p([run(text, { bold: true })], { alignment: AlignmentType.RIGHT });
}

