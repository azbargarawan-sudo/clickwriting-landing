const HE = { ascii: 'Times New Roman', hAnsi: 'Times New Roman', cs: 'David', eastAsia: 'David' };
const EN = { ascii: 'Times New Roman', hAnsi: 'Times New Roman', cs: 'Times New Roman' };
const AR = { ascii: 'Times New Roman', hAnsi: 'Times New Roman', cs: 'Traditional Arabic', eastAsia: 'Traditional Arabic' };
const LINE = 480; // מרווח כפול
const CM = 567;   // 1 ס"מ ב-DXA

function run(text, o = {}) {
  return new TextRun({ text, rightToLeft: true, font: HE, size: 24, sizeComplexScript: 24, ...o });
}
// פסקה עברית רגילה. מקבל מחרוזת או מערך של קטעים {t, b, i}
function p(content, o = {}) {
  const segs = Array.isArray(content) ? content : [{ t: content }];
  const children = segs.map(s => run(s.t, { bold: !!s.b, italics: !!s.i, ...(s.run || {}) }));
  return new Paragraph({
    bidirectional: true,
    alignment: o.align || AlignmentType.BOTH,
    spacing: { line: o.line || LINE, before: o.before || 0, after: o.after || 0 },
    indent: o.indent,
    numbering: o.numbering,
    keepNext: o.keepNext,
    pageBreakBefore: o.pageBreakBefore,
    children,
  });
}
function h1(text, o = {}) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1, bidirectional: true, pageBreakBefore: o.noBreak ? false : true,
    spacing: { line: LINE, before: 0, after: 240 },
    children: [run(text, { bold: true, size: 32, sizeComplexScript: 32 })],
  });
}
function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2, bidirectional: true, keepNext: true,
    spacing: { line: LINE, before: 240, after: 120 },
    children: [run(text, { bold: true, size: 28, sizeComplexScript: 28 })],
  });
}
function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3, bidirectional: true, keepNext: true,
    spacing: { line: LINE, before: 120, after: 0 },
    children: [run(text, { bold: true, size: 24, sizeComplexScript: 24 })],
  });
}
const empty = () => new Paragraph({ spacing: { line: LINE }, children: [run('')] });

let numInstance = 0;
function numbered(items) {
  numInstance += 1;
  const inst = numInstance;
  return items.map(t => p(t, { numbering: { reference: 'nums', level: 0, instance: inst }, align: AlignmentType.START }));
}
function bullets(items, opts = {}) {
  return items.map(t => p(t, { numbering: { reference: 'bullets', level: 0 }, align: AlignmentType.START, ...opts }));
}

// רשומה עברית ברשימת המקורות
function refHe(segs) {
  return new Paragraph({
    bidirectional: true, alignment: AlignmentType.START,
    indent: { start: 709, hanging: 709 }, spacing: { line: LINE },
    children: segs.map(s => run(s.t, { italics: !!s.i })),
  });
}
// רשומה לועזית ברשימת המקורות
function refEn(segs) {
  return new Paragraph({
    bidirectional: false, alignment: AlignmentType.LEFT,
    indent: { left: 709, hanging: 709 }, spacing: { line: LINE },
    children: segs.map(s => new TextRun({ text: s.t, italics: !!s.i, font: EN, size: 24 })),
  });
}
// פסקה בערבית
function ar(content, o = {}) {
  const segs = Array.isArray(content) ? content : [{ t: content }];
  return new Paragraph({
    bidirectional: true, alignment: o.align || AlignmentType.START,
    spacing: { line: LINE }, numbering: o.numbering, indent: o.indent,
    children: segs.map(s => new TextRun({ text: s.t, rightToLeft: true, font: AR, size: 26, sizeComplexScript: 26, bold: !!s.b })),
  });
}
function arNumbered(items) {
  numInstance += 1;
  const inst = numInstance;
  return items.map(t => ar(t, { numbering: { reference: 'nums', level: 0, instance: inst } }));
}

function cell(text, width, o = {}) {
  return new TableCell({
    width: { size: width, type: WidthType.DXA },
    shading: o.head ? { type: ShadingType.CLEAR, fill: 'E7E6E6', color: 'auto' } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [p(text, { align: AlignmentType.START, line: 276, run: o.head ? { bold: true } : {} })].map(par => par),
  });
}

