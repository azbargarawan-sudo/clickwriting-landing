from docx.oxml import OxmlElement

FONT = "David"

def _rtl_pPr(p):
    pPr = p._p.get_or_add_pPr()
    if pPr.find(qn('w:bidi')) is None:
        pPr.append(OxmlElement('w:bidi'))

def _style_run(r, size=12, bold=False, underline=False):
    r.font.name = FONT
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.underline = underline
    rPr = r._r.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    for a in ('w:ascii', 'w:hAnsi', 'w:cs'):
        rFonts.set(qn(a), FONT)
    szCs = OxmlElement('w:szCs'); szCs.set(qn('w:val'), str(size * 2)); rPr.append(szCs)
    if bold:
        rPr.append(OxmlElement('w:bCs'))
    rPr.append(OxmlElement('w:rtl'))

def para(doc, text="", size=12, bold=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
         space_after=6, underline=False):
    p = doc.add_paragraph()
    _rtl_pPr(p)
    p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    if text:
        r = p.add_run(text)
        _style_run(r, size=size, bold=bold, underline=underline)
    return p

