add(P('הראיונות נערכו בערבית מדוברת, לפי בחירת המרואיינות. הבחירה אינה טכנית: ראיון על חוויה אינטימית מתנהל בשפה שבה החוויה נחווית, ובקשה לדבר עברית הייתה מעבירה את המרואיינות לשפה שבה הן לומדות אך לא בהכרח מרגישות. התמלול נעשה תחילה בערבית, מילה במילה, ורק אחר כך תורגם לעברית.'));
add(P('התרגום הוא פעולה פרשנית ולא העברה נייטרלית, ולכן ננקטו שני צעדים: ביטויים שאין להם מקבילה מדויקת בעברית נשמרו בשפת המקור בתוך התמליל, בכתיב ערבי ובתעתיק עברי, ולצדם תרגום; ושתי המרואיינות שקראו את סיכום התימות התבקשו לאשר גם את תרגום הציטוטים שלהן. אחת מהן תיקנה תרגום אחד וטענה שהמילה שנבחרה חריפה מדי.'));
add(H2('2.5 ניתוח הנתונים'));
add(P('התמלול כלל את שאלות המראיינת, שתיקות וצחוק, מתוך תפיסה שהצורה שבה נאמר דבר היא חלק מן הנתון ולא עטיפה שלו (שקדי, 2003). הניתוח נערך בשיטת הניתוח התמטי הרפלקסיבי, לפי ששת השלבים שמתארות בראון וקלארק: היכרות עם החומר, קודים ראשוניים, חיפוש תימות, בחינה חוזרת, הגדרה ומתן שם, וכתיבה (Braun & Clarke, 2022).'));
add(P('בקידוד הפתוח נוצרו חמישים ושמונה קודים ראשוניים, כגון "שעות באוטו", "חשבון מול חמאתי" ו"לחשוב בערבית ולכתוב בעברית". הם קובצו לחמישה עשר אשכולות, ומהם לחמש תימות ולשלוש קטגוריות (נספח 3). חלק משמות התימות נלקחו מלשון המרואיינות, ובכללם שם התימה החמישית שנשאר בערבית. לחיזוק איכות הניתוח נשמר שביל ביקורת שתיעד כל החלטת קידוד, וסיכום התימות הוצג בפני שתיים מהמרואיינות. בגישה הרפלקסיבית איכות נמדדת בשקיפות ההכרעות הפרשניות ולא בהתאמה בין מקודדים (Braun & Clarke, 2022).'));
add(H2('2.6 סוגיות אתיות'));
add(P('כל המרואיינות חתמו על טופס הסכמה מדעת (נספח 4), שהוצג בעברית ובערבית וכלל את מטרת המחקר, ההסכמה להקלטה, ההתחייבות למחוק את קובץ האודיו לאחר התמלול, והזכות להפסיק או להשמיט דברים בכל שלב. זכות זו מומשה בראיון השלישי.'));
add(P('שמירת האנונימיות מציבה כאן קושי מיוחד: ביישוב שבו כולם מכירים זה את זה, צירוף של תחום לימודים, מספר ילדים ומקום עבודה עלול לזהות אישה גם בלי שמה. לכן הוחלפו השמות בשמות בדויים, שמות היישובים בתיאור כללי, שמות המעסיקים הושמטו וגילי הילדים עוגלו. פרט מזהה נוסף, מקצועו של אחד מבני הזוג, הוסר לחלוטין.'));
add(P('מעבר לנהלים הפורמליים עלו מה שגילמין וגילם מכנות רגעים בעלי חשיבות אתית, מצבים בלתי צפויים שאינם מכוסים בטופס ההסכמה ודורשים הכרעה בזמן אמת (Guillemin & Gillam, 2004). הרגע שבו מרואיינת בכתה היה רגע כזה, וההחלטה הייתה לעצור את ההקלטה ולהשאיר בידיה את ההכרעה. סוגיה נוספת נגעה לקרבת המראיינת לשדה, שהיא בת אותה חברה. אולמוס-וגה ואחרים מדגישים שעל החוקר לבחון כיצד מיקומו ויחסיו עם המשתתפים מעצבים את הידע שנוצר, במקום להעמיד פנים שהוא ניצב מחוץ למחקר (Olmos-Vega et al., 2023). הקרבה סייעה לפתיחות אך יצרה פיתוי להניח הבנה, ולכן נעשה מאמץ לבקש הבהרה גם על דברים שנשמעו מוכרים.'));

// ============ 4. findings ============
add(H1('3. ממצאים'));
add(P('הניתוח העלה חמש תימות. סדר הצגתן נע מן החוץ פנימה: מן הארגון הפיזי של היום, דרך העולם הפנימי, אל מעגלי המשפחה, המפגש עם המוסדות, ולבסוף המשמעות שמייחסות המרואיינות ללימודים.'));

add(H2('3.1 "היום מתחיל בחמש": זמן, מרחק ונסיעות'));
add(P('בשלושת הראיונות תואר היום לא כרצף שעות אלא כמלאי מוגבל שיש לחלק בין תובעים. אצל שתיים מהן נגרע מן המלאי נתח קבוע שאין עליו שליטה, הנסיעה.'));
add(P('סאמייה פתחה כך: "היום מתחיל בחמש, לפני שהם קמים, כי זה הזמן היחיד שהבית שקט. אני עושה שעה, ואז בשש הקטנה מתעוררת וזהו, נגמר."'));
add(Q('מהיישוב עד המכללה זה שעה וחצי בבוקר, אם אין פקק. אני יוצאת בשש וחצי ומגיעה לשיעור של שמונה. אחרי השיעור האחרון אני רצה לאוטו כדי להספיק לאסוף את הקטן, ובדרך חזרה זה שוב שעה וחצי. יש לי שלוש שעות ביום שאני יושבת באוטו. אנשים אומרים לי תלמדי בנסיעה, אני נוהגת. (רים)'));
add(P('הנסיעה אינה זמן פנוי ואינה זמן עבודה. היא נגרעת מן היום בלי להיחשב לאיש, ובשלושת הראיונות לא הוזכרה כשנשאלו על עומס אלא רק כשהתבקשו לתאר שעה אחר שעה. עיינא ניסחה את המסקנה: "השינה היא הדבר היחיד שאפשר לקצץ בו." כשהזמן מחולק כך, אף נוכחות אינה שלמה, וזו התימה הבאה.'));

add(H2('3.2 "לא אשמה, אחריות": פיצול הקשב והחשבון הפנימי'));
add(P('התימה השנייה עוסקת בנוכחות חלקית בכל מקום ובמנגנון ההצדקה הפנימי שמלווה אותה. שמה נלקח מתיקון שהציעה אחת המרואיינות למילה שהמראיינת השתמשה בה.'));
add(P('עיינא תיארה את הפיצול בקצרה: "אני יושבת בהרצאה וחושבת על הגן. אני בגן וחושבת על המבחן. אין רגע אחד שאני נמצאת רק במקום אחד." רים דחתה את המסגור הרגשי שהוצע לה: "לא אשמה. אחריות. אני אחראית, וזה לא אותו דבר."'));
add(P('ההבחנה אינה משחק מילים. סאמייה הסבירה אותה במונחים חברתיים: "אם משהו קורה לילד, אף אחד לא ישאל איפה היה אבא. ישאלו איפה הייתה האמא." מדובר פחות ברגש פרטי ויותר בעמדה שהחברה מקצה. עתאמנה מצאה בקרב אימהות פלסטיניות בישראל שהאחריות האימהית מובנית כמטלה מוסרית רחבה, המשתרעת גם על הישגי הילדים ועל שלומם הרגשי, ושהאימהות פועלות בתוכה כסוכנות ולא רק כקורבנות (Athamneh, 2024). המרואיינות כאן אינן מתארות את עצמן כנשברות תחת האחריות אלא כמנהלות אותה, ומכאן השאלה מי מסייע להן בפועל.'));

add(H2('3.3 "בלי חמאתי אין תואר": המשפחה המורחבת כתשתית וכחוב'));
add(P('התימה השלישית עוסקת בתשתית האנושית שמאפשרת את השילוב, ובמחיר הסמוי שהיא גובה.'));
add(P('סאמייה אמרה: "חמאתי (حماتي, חמותי) לוקחת אותם ארבעה ימים בשבוע. בלעדיה אין תואר, פשוט אין", ומיד הוסיפה: "אני מרגישה שאני חייבת לה. היא אף פעם לא אמרה מילה, זה אני." התמיכה מתוארת כהלוואה. היא מאפשרת את הלימודים ובו בזמן פותחת חשבון שאינו נסגר. רים, שאין לה סידור קבוע, תיארה את הצד השני: "אין מעון לגיל שנה ביישוב שלי. אין. אז זה חמאתי או כלום."'));
add(P('נקודה שנייה עלתה בדבריה של עיינא: "בעלי עוזר המון, באמת." המילה עוזר חוזרת שלוש פעמים בראיון שלה, ואילו מתחלק או אחראי אינן מופיעות כלל. הפועל משמר את הנחת היסוד שהאחריות שייכת לאישה ושהגבר תורם לה, וזהו הפער שתיארה הוקשילד בין הצהרה על שוויון לבין חלוקת העבודה בפועל (Hochschild, 1989). צבאח-כרכבי מראה שבמשפחות ערביות-פלסטיניות בישראל החלוקה נותרת ממוגדרת אך אינה אחידה, ומשתנה לפי משאבי המשפחה ומיקומה החברתי (Sabbah-Karkabi, 2024). השונות בין שלוש המרואיינות ממחישה זאת.'));
add(P('נקודה שלישית נוגעת לכך שאותה משפחה שמחזיקה גם מתבוננת. רים ניסחה זאת כך: "שו ביחכו א-נאס (شو بيحكوا الناس, מה יגידו האנשים). זה לא משפט שמישהו אומר לך. זה כמו מזג אוויר, זה פשוט שם." התמיכה והפיקוח מגיעים מאותו מקור, ולכן אי אפשר לקבל את הראשונה ולהתנער מן השני. כשהמעגל המשפחתי אינו מספיק, נותר לפנות אל המוסדות.'));

add(H2('3.4 "המערכת לא בנויה בשבילנו": מרחק, שפה והתאמות שניתנות כטובה'));
add(P('התימה הרביעית עוסקת במפגש עם ארגונים, ובתלות בשיקול דעת אישי במקום בכללים.'));
add(Q('המבחן נקבע לשמונה בבוקר ביום שאין גן. שאלתי אם אפשר מועד אחר, אמרו לי שיש מועד ב\'. מועד ב\' זה לא פתרון, זה עונש, כי אז אני לומדת את זה פעמיים ומאבדת עוד שבוע. אף אחד לא חשב שיש כאלה שהבוקר שלהן לא פנוי. (רים)'));
add(P('לצד מועדי הבחינות עלה חסם שאינו מופיע בשום נוהל. עיינא תיארה אותו כך: "אני חושבת בערבית וכותבת בעברית. זה לוקח לי פי שניים זמן, וזה לא בגלל שאני לא מבינה את החומר." זהו החסם שתיארו אראר וחאג\' יחיא, שהצביעו על השפה ועל המרחק כמכשולים מבניים בדרכם של סטודנטים ערבים (Arar & Haj-Yehia, 2016). כשחסם השפה נפגש עם שלוש שעות נסיעה ועם היעדר מעון ביישוב, הזמן שנותר ללימודים מצטמצם פעמיים.'));
add(P('סאמייה תיארה שני קצוות באותו סמסטר: "יש מרצה שאמרה לי תביאי אותה, שתשב מאחורה עם טאבלט. ויש מרצה שאמר לי שזה לא מעון." ההבדל אינו נעוץ במדיניות אלא באדם. ההתאמות קיימות, אך הן ניתנות כטובה אישית ולא כזכות, ולכן אינן ניתנות לתכנון ולא לתביעה. הממצא תואם את מסקנתם של סאלי ואחרים, שלפיה הצלחתן של אימהות סטודנטיות נשענת על גורם מוסדי בודד שנקרה בדרכן ולא על מדיניות סדורה, ולכן היא מקרית מטבעה (Sallee et al., 2025). מכאן מתחדדת השאלה מדוע בכל זאת ממשיכות המרואיינות ללמוד.'));

add(H2('3.5 "בדי אכון אישי": התואר כזהות וכביטחון'));
add(P('התימה החמישית מציגה את הצד שאינו נזק, ושמה נשאר בערבית משום שהניסוח העברי מאבד ממנו.'));
add(P('עיינא אמרה: "בדי אכון אישי (بدي أكون إشي, אני רוצה להיות משהו). לא במקום אמא. ביחד עם." רים הוסיפה נימוק אחר לגמרי: "אם מחר אני לבד, אני צריכה לדעת שאני יכולה להחזיק את הילדים. תעודה זה ביטחון." סאמייה קשרה את הלימודים לדמות שהיא מציגה בפני ילדיה: "אני רוצה שהבת שלי תראה אותי לומדת."'));
add(Q('בהתחלה נרשמתי בשביל משכורת יותר טובה, בלי רומנטיקה. אבל אני יושבת בשיעור, פתאום מדברים על משהו ואני חושבת על זה שעתיים אחר כך, וזה החלק היחיד ביום שאני חושבת בו על משהו שהוא לא לוגיסטיקה. אז זה כבר לא רק הכסף. (סאמייה)'));
add(P('שלושת הנימוקים שונים: זהות, ביטחון כלכלי ומודל לילדה. משותף להם שהלימודים מתוארים בלשון בעלות ובלשון עתיד, בעוד ששאר תחומי החיים מתוארים בהווה דחוק. התפקיד הכפול הזה, מקור עומס ומקור זהות בבת אחת, הוא הממצא המרכזי שאליו מתייחס הדיון.'));

// ============ 5. discussion ============
add(H1('4. דיון'));
