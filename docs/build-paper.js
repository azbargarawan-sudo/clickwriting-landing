const HE = 'David';
const EN = 'Times New Roman';
const DOUBLE = { line: 480, lineRule: 'auto', after: 0 };
const HANG = 709; // 1.25 cm

// ---------- helpers ----------
function run(text, opts = {}) {
  return new TextRun({ text, font: HE, size: 24, rightToLeft: true, ...opts });
}

function P(text, opts = {}) {
  return new Paragraph({
    bidirectional: true,
    alignment: opts.align || AlignmentType.JUSTIFIED,
    spacing: { ...DOUBLE, ...(opts.spacing || {}) },
    indent: opts.indent,
    children: [run(text, { bold: opts.bold, italics: opts.italics })],
  });
}

function EMPTY() {
  return new Paragraph({ bidirectional: true, spacing: DOUBLE, children: [run('')] });
}

function H1(text, { pageBreak = false } = {}) {
  const kids = [];
  if (pageBreak) kids.push(new PageBreak());
  kids.push(run(text, { bold: true, size: 28 }));
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { line: 480, lineRule: 'auto', before: 240, after: 120 },
    children: kids,
  });
}

function H2(text) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: { line: 480, lineRule: 'auto', before: 120, after: 0 },
    children: [run(text, { bold: true })],
  });
}

// block quote (40+ words): hanging indent from the right margin, no quote marks
function Q(text) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.JUSTIFIED,
    spacing: DOUBLE,
    indent: { start: HANG },
    children: [run(text)],
  });
}

// transcript line
function SPK(name, text) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.JUSTIFIED,
    spacing: DOUBLE,
    children: [run(name + ': ', { bold: true }), run(text)],
  });
}

function REF_HE(text) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing: DOUBLE,
    indent: { start: HANG, hanging: HANG },
    children: [run(text)],
  });
}

function REF_EN(text) {
  return new Paragraph({
    bidirectional: false,
    alignment: AlignmentType.LEFT,
    spacing: DOUBLE,
    indent: { left: HANG, hanging: HANG },
    children: [new TextRun({ text, font: EN, size: 24 })],
  });
}

function cell(text, { bold = false, width, shade } = {}) {
  return new TableCell({
    width: { size: width, type: WidthType.DXA },
    shading: shade ? { type: ShadingType.CLEAR, fill: shade, color: 'auto' } : undefined,
    margins: { top: 60, bottom: 60, left: 90, right: 90 },
    children: [new Paragraph({
      bidirectional: true,
      alignment: AlignmentType.RIGHT,
      spacing: { line: 240, lineRule: 'auto' },
      children: [run(text, { bold })],
    })],
  });
}

function table(widths, rows) {
  const total = widths.reduce((a, b) => a + b, 0);
  return new Table({
    visuallyRightToLeft: true,
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    rows: rows.map((cells, ri) => new TableRow({
      tableHeader: ri === 0,
      children: cells.map((t, ci) => cell(t, {
        bold: ri === 0, width: widths[ci], shade: ri === 0 ? 'E8E8E8' : undefined,
      })),
    })),
  });
}

