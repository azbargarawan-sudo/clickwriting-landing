add(P('מעבר לנהלים הפורמליים עלו מה שגילמין וגילם מכנות רגעים בעלי חשיבות אתית, מצבים בלתי צפויים שאינם מכוסים בטופס ההסכמה ודורשים הכרעה בזמן אמת (Guillemin & Gillam, 2004). הרגע שבו מרואיינת בכתה היה רגע כזה, וההחלטה הייתה לעצור את ההקלטה ולהשאיר בידיה את ההכרעה אם להמשיך. סוגיה נוספת נגעה לקרבת המראיינת לשדה. אולמוס-וגה ואחרים מדגישים שעל החוקר לבחון באופן שיטתי כיצד מיקומו ויחסיו עם המשתתפים מעצבים את הידע שנוצר, במקום להעמיד פנים שהוא ניצב מחוץ למחקר (Olmos-Vega et al., 2023). הקרבה סייעה לפתיחות אך יצרה גם פיתוי להשלים משפטים ולהניח הבנה, ולכן נעשה מאמץ לבקש הבהרה גם על דברים שנשמעו מוכרים. בסיום כל ראיון הוצע למרואיינת עותק של התמלול ושל העבודה, ונמסר לה מידע על שירות הייעוץ לסטודנטים במכללה, בלי לקשור זאת לתוכן שנאמר.'));

// ============ 4. findings ============
add(H1('3. ממצאים'));
add(P('הניתוח העלה חמש תימות. סדר הצגתן נע מן החוץ פנימה: מן הארגון הפיזי של היום, דרך העולם הפנימי, אל מעגלי התמיכה, המפגש עם המוסדות, ולבסוף המשמעות שמייחסות המרואיינות ללימודים.'));

add(H2('3.1 "היום מתחיל בחמש": הזמן כמשאב שנגמר'));
add(P('בכל שלושת הראיונות תואר היום לא כרצף של שעות אלא כמלאי מוגבל שיש לחלק בין תובעים. הזמן אינו מאורגן, הוא מוקצה.'));
add(P('נועה פתחה את תיאור היום שלה כך: "היום מתחיל בחמש, לפני שהם קמים, כי זה הזמן היחיד שהבית שקט. אני עושה שעה של קריאה, ואז בשש הקטן מתעורר וזהו, נגמר."'));
add(Q('אנשים חושבים שסטודנטית זה לישון עד עשר. אני קמה בחמש וחצי, מכינה סנדוויץ\', מורידה אותו לגן, נוסעת למכללה, יוצאת מההרצאה האחרונה רצה למשמרת, בשמונה אוספת אותו מהשכנה, מקלחת, סיפור, ובעשר וחצי אני פותחת מחשב. הזמן שלי הוא מה שנשאר אחרי כולם. (טלי)'));
add(P('שתי האמירות מציגות אותו מבנה: יש שעות שהן של אחרים, ויש שארית. השארית ממוקמת בקצוות היממה, לפני שהבית מתעורר ואחרי שהוא נרדם, כלומר בשעות שבהן הגוף אמור לנוח. השינה מתפקדת כעתודה, המשאב היחיד שאפשר למשוך ממנו בלי לפגוע באיש, כפי שניסחה שיר: "השינה היא התקציב הגמיש היחיד שיש לי." כשהזמן מחולק כך, אף נוכחות אינה שלמה, וזו התימה הבאה.'));

add(H2('3.2 "בשום מקום אני לא שלמה": פיצול הקשב והחשבון הפנימי'));
add(P('התימה השנייה עוסקת בחוויה של נוכחות חלקית בכל מקום, ובמנגנון ההצדקה הפנימי שמלווה אותה.'));
add(P('שיר תיארה זאת בקצרה: "אני יושבת בהרצאה וחושבת על הגן. אני בגן וחושבת על המבחן. אין רגע אחד שאני נמצאת רק במקום אחד." טלי הצביעה על התמשכות הרגש מעבר לרגע עצמו: "כשהוא בוכה בבוקר בגן, כל היום זה יושב לי פה", ובאומרה זאת הצביעה על החזה.'));
add(P('בולט המשפט של נועה: "אם הייתי מפסיקה ללמוד הייתי אמא יותר טובה. אני יודעת שזה לא נכון, אבל אני חושבת את זה." המשפט מכיל את שני קצות הסתירה בבת אחת, את האמונה ואת הידיעה שהיא שגויה, בלי שהאחת מבטלת את השנייה. זו אינה טעות בחשיבה אלא ביטוי למה שהייז תיארה כסתירה תרבותית המוטלת על אימהות, הנדרשות בעת ובעונה אחת להשקעה בלתי מוגבלת בילדים ולהישגיות כלכלית (Hays, 1996). האשמה מופנית פנימה ולא כלפי החברה שמציבה את הדרישה הכפולה, ואף לא אחת מהמרואיינות הזכירה את בן זוגה כמושא לביקורת. מכאן עולה השאלה מי כן מחזיק אותן.'));

add(H2('3.3 "מי מחזיק אותי": רשתות תמיכה, גלויות וסמויות'));
add(P('התימה השלישית עוסקת בתשתית האנושית שמאפשרת את השילוב, ובמחיר הסמוי שהיא גובה.'));
add(P('נועה אמרה: "חמותי לוקחת אותם שלוש פעמים בשבוע. בלעדיה לא הייתי סטודנטית, פשוט לא", ומיד הוסיפה: "אני מרגישה שאני חייבת לה. היא אף פעם לא אמרה מילה, זה אני." התמיכה מתוארת כהלוואה: היא מאפשרת את הלימודים ובו בזמן פותחת חשבון רגשי שאינו נסגר. טלי, אם חד הורית, תיארה מציאות אחרת: "אין לי גב. יש לי שכנה טובה ותשלום לבייביסיטר, וזה מה יש." בהיעדר משפחה מורחבת זמינה התמיכה הופכת למוצר שנרכש, ועלותה מוטלת על מי שהכנסתה ממילא נמוכה. אנדרדה ואחרים מצאו שהאסטרטגיות שמפתחים הורים לומדים שלובות בתמיכה החברתית שהם מצליחים לגייס, ולא רק במידת הנחישות שלהם (Andrade et al., 2024).'));
add(P('נקודה שלישית עלתה בדבריה של שיר: "בן זוגי עוזר המון, באמת." המילה עוזר חוזרת פעמיים בראיון שלה, ואילו מילים כמו מתחלק או אחראי אינן מופיעות כלל. הפועל הזה משמר את הנחת היסוד שהאחריות שייכת לאישה ושהגבר תורם לה, וזהו הפער שתיארה הוקשילד בין הצהרה על שוויון לבין חלוקת העבודה בפועל (Hochschild, 1989). כשהמעגל הפרטי אינו מספיק, נותר לפנות אל המוסדות.'));

add(H2('3.4 "המערכת לא בנויה בשבילנו": מוסד הלימודים ומקום העבודה'));
add(P('התימה הרביעית עוסקת במפגש עם ארגונים, ובתלות בשיקול דעת אישי במקום בכללים.'));
add(Q('המבחן נקבע לשמונה בבוקר ביום שאין גן. שאלתי אם אפשר מועד אחר, אמרו לי שיש מועד ב\'. מועד ב\' זה לא פתרון, זה עונש, כי אז אני לומדת את זה פעמיים ומאבדת עוד שבוע. אף אחד לא חשב שיש כאלה שהבוקר שלהן לא פנוי. (טלי)'));
add(P('שיר תיארה שני קצוות באותו סמסטר: "יש מרצה שאמרה לי תביאי אותה, שתשב מאחורה עם טאבלט. ויש מרצה שאמר לי שזה לא מעון." ההבדל בין השניים אינו נעוץ במדיניות אלא באדם. נועה אמרה דבר דומה על מקום עבודתה: "המנהלת שלי בסדר איתי, אבל זה בגלל שהיא בסדר, לא בגלל שמגיע לי."'));
add(P('שלוש האמירות מצביעות על אותו מנגנון: ההתאמות קיימות, אך הן ניתנות כטובה אישית ולא כזכות. לכן אינן ניתנות לתכנון ולא לתביעה, ומחייבות את הסטודנטית להציג את עצמה שוב ושוב כמקרה חריג הראוי לחמלה. הממצא תואם את מסקנתם של סאלי ואחרים, שלפיה הצלחתן של אימהות סטודנטיות נשענת על גורם מוסדי בודד שנקרה בדרכן ולא על מדיניות סדורה, ולכן היא מקרית מטבעה (Sallee et al., 2025). מכאן מתחדדת השאלה מדוע בכל זאת ממשיכות המרואיינות ללמוד.'));

add(H2('3.5 "זה בשבילי, לא רק בשבילם": הלימודים כהשקעה בזהות'));
add(P('התימה החמישית מציגה את הצד שאינו נזק. הלימודים אינם מתוארים רק כעומס נוסף אלא כמרחב בעל ערך עצמאי.'));
add(P('טלי אמרה: "התואר הזה הוא הדבר היחיד שהוא רק שלי. הכל בבית שייך לו, וזה שלי." נועה קשרה את הלימודים לדמות שהיא מציגה בפני ילדיה: "אני רוצה שהבת שלי תראה אותי לומדת, לא רק מנקה."'));
add(Q('בהתחלה נכנסתי לתואר בשביל משכורת יותר טובה, בלי רומנטיקה. אבל אני יושבת בשיעור, פתאום מדברים על משהו ואני חושבת שעתיים אחר כך על מה שנאמר שם, וזה החלק היחיד ביום שאני חושבת בו על משהו שהוא לא לוגיסטיקה. אז זה כבר לא רק הכסף. (שיר)'));
add(P('בשלושת הראיונות הלימודים מתפקדים כטריטוריה שאינה נחלקת עם אחרים. הם מתוארים בלשון בעלות ובלשון עתיד, בעוד ששאר תחומי החיים מתוארים בהווה דחוק. התפקיד הכפול הזה, מקור עומס ומקור זהות בבת אחת, הוא הממצא המרכזי שאליו מתייחס הדיון.'));

// ============ 5. discussion ============
add(H1('4. דיון'));
add(P('הממצאים מלמדים ששאלת השילוב אינה שאלה של ניהול זמן. שלוש המרואיינות מנהלות את זמנן היטב, ובכל זאת מתארות מחסור קבוע. גרינהאוס וביוטל הבחינו בין קונפליקט מבוסס זמן, קונפליקט מבוסס מאמץ וקונפליקט מבוסס התנהגות (Greenhaus & Beutell, 1985). כאן בולטים שני הסוגים הראשונים ומופיעים יחד: הזמן חסר, וגם כשהוא נמצא, המשאב הנפשי שנדרש כדי להשתמש בו כבר הוצא במקום אחר. תיאורה של טלי, הפותחת מחשב בעשר וחצי בלילה, ממחיש שהקצאת שעה אינה שקולה להקצאת יכולת ללמוד בה. ממצאיה של קוליק, שלפיהם נשים דיווחו על קונפליקט גבוה במיוחד במפגש שבין המשפחה ללימודים, מקבלים כאן פנים קונקרטיות (Kulik, 2025).'));
add(P('התימה השנייה מבהירה מדוע העומס נחווה כאשמה ולא ככשל מערכתי. כשאידיאל האימהות דורש השקעה בלתי מוגבלת, כל שעה שמוקדשת ללימודים נרשמת כגירעון (Hays, 1996), והמרואיינות אינן מתארות את המוסד או את בן הזוג כאחראים למחסור אלא את עצמן. המשפט של שיר על בן זוג שעוזר ממחיש את הפער שתיארה הוקשילד בין אידיאולוגיה מוצהרת לבין חלוקת עבודה בפועל: השפה עצמה מקצה את האחריות לאישה ומגדירה את הגבר כתורם מרצון (Hochschild, 1989).'));
add(P('הממצא על ההתאמות הניתנות כטובה אישית מתכתב עם סאלי ואחרים, שהראו שאימהות סטודנטיות נעות בין מוסדות שבהם קיים מערך שירותים שלם לבין מוסדות שבהם אין דבר, ושבתווך ניצב לרוב אדם אחד שהחליט לעזור (Sallee et al., 2025). התאמה שאינה כתובה אינה ניתנת לתכנון, וסטודנטית שנאלצת לבקש אותה מחדש מכל מרצה משלמת מחיר נוסף בזמן ובכבוד.'));
add(P('התימה החמישית מסייגת את התמונה. לצד קונפליקט תפקידים בחנה קוליק גם העשרת תפקידים, כלומר תרומה חיובית של תפקיד אחד למשנהו, והראתה ששני התהליכים מתקיימים אצל אותם הורים בעת ובעונה אחת (Kulik, 2025). דבריה של טלי על התואר כדבר היחיד ששייך לה בלבד מצביעים על העשרה כזאת. מכאן שמסגור השילוב כבעיה בלבד מחמיץ חלק מהותי מן החוויה, ומדיניות שתבקש להקל באמצעות צמצום דרישות עלולה לפגוע דווקא במה שמחזיק אותן.'));
add(P('מכאן שלוש מסקנות יישומיות: פרסום לוח בחינות בתחילת הסמסטר והימנעות משיבוץ בחינות בשעות הבוקר המוקדמות ביום שבו מסגרות החינוך סגורות; ניסוח נוהל מוסדי כתוב להתאמות לסטודנטים הורים, שיחליף את ההסתמכות על שיקול דעתו של המרצה; וגיבוש מרחב עמיתים לסטודנטיות אימהות, שכן המרואיינות תיארו את הבידוד כמכביד לא פחות מן העומס. מגבלות העבודה ברורות: שלוש מרואיינות אינן מדגם, כולן לומדות במוסד אחד, וכולן בחרו להשתתף, כלומר היה להן כוח לספר. נשים שנשרו מן הלימודים אינן מיוצגות כאן, ודווקא סיפורן היה עשוי לשנות את התמונה.'));

// ============ 6. process reflection ============
add(H1('5. תהליך ביצוע העבודה'));
