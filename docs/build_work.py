FONT = "David"

def _rtl_pPr(p):
    pPr = p._p.get_or_add_pPr()
    if pPr.find(qn('w:bidi')) is None:
        bidi = OxmlElement('w:bidi')
        pPr.append(bidi)

def _style_run(r, size=12, bold=False, color=None):
    r.font.name = FONT
    r.font.size = Pt(size)
    r.font.bold = bold
    rPr = r._r.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    for a in ('w:ascii', 'w:hAnsi', 'w:cs'):
        rFonts.set(qn(a), FONT)
    # complex-script size/bold so Hebrew actually gets them
    szCs = OxmlElement('w:szCs'); szCs.set(qn('w:val'), str(size * 2)); rPr.append(szCs)
    if bold:
        bCs = OxmlElement('w:bCs'); rPr.append(bCs)
    rtl = OxmlElement('w:rtl'); rPr.append(rtl)
    if color:
        r.font.color.rgb = color

def para(doc_or_cell, text="", size=12, bold=False, align=None, space_after=6, line=1.15):
    p = doc_or_cell.add_paragraph()
    _rtl_pPr(p)
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.line_spacing = line
    if text:
        r = p.add_run(text)
        _style_run(r, size=size, bold=bold)
    return p

def bullet(doc, text, size=12):
    p = para(doc, "", size=size)
    r = p.add_run("• " + text)
    _style_run(r, size=size)
    p.paragraph_format.right_indent = Cm(0.4)
    return p

def heading(doc, text, size=16):
    p = para(doc, text, size=size, bold=True, space_after=8)
    return p

def add_hyperlink(p, url, text, size=12):
    part = p.part
    r_id = part.relate_to(url, RT.HYPERLINK, is_external=True)
    hl = OxmlElement('w:hyperlink')
    hl.set(qn('r:id'), r_id)
    new_r = OxmlElement('w:r')
    rPr = OxmlElement('w:rPr')
    rFonts = OxmlElement('w:rFonts')
    for a in ('w:ascii', 'w:hAnsi', 'w:cs'):
        rFonts.set(qn(a), FONT)
    rPr.append(rFonts)
    sz = OxmlElement('w:sz'); sz.set(qn('w:val'), str(size * 2)); rPr.append(sz)
    szCs = OxmlElement('w:szCs'); szCs.set(qn('w:val'), str(size * 2)); rPr.append(szCs)
    color = OxmlElement('w:color'); color.set(qn('w:val'), '0563C1'); rPr.append(color)
    u = OxmlElement('w:u'); u.set(qn('w:val'), 'single'); rPr.append(u)
    new_r.append(rPr)
    t = OxmlElement('w:t'); t.text = text; t.set(qn('xml:space'), 'preserve')
    new_r.append(t)
    hl.append(new_r)
    p._p.append(hl)
    return hl

def make_table(doc, rows, cols, widths=None):
    t = doc.add_table(rows=rows, cols=cols)
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    tblPr = t._tbl.tblPr
    bidi = OxmlElement('w:bidiVisual')
    tblPr.append(bidi)
    if widths:
        t.autofit = False
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    return t

def cell_text(cell, text, size=11, bold=False, shade=None):
    cell.paragraphs[0].text = ""
    first = True
    for chunk in text.split("\n"):
        if first:
            p = cell.paragraphs[0]
            first = False
        else:
            p = cell.add_paragraph()
        _rtl_pPr(p)
        p.paragraph_format.space_after = Pt(2)
        if chunk:
            r = p.add_run(chunk)
            _style_run(r, size=size, bold=bold)
    if shade:
        tcPr = cell._tc.get_or_add_tcPr()
        shd = OxmlElement('w:shd')
        shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto'); shd.set(qn('w:fill'), shade)
        tcPr.append(shd)

def cell_with_link(cell, before, url, linktext, after="", size=11):
    cell.paragraphs[0].text = ""
    p = cell.paragraphs[0]
    _rtl_pPr(p)
    p.paragraph_format.space_after = Pt(2)
    if before:
        for chunk in before.split("\n"):
            if p.runs or p._p.findall(qn('w:hyperlink')):
                p = cell.add_paragraph(); _rtl_pPr(p); p.paragraph_format.space_after = Pt(2)
            r = p.add_run(chunk); _style_run(r, size=size)
        p = cell.add_paragraph(); _rtl_pPr(p); p.paragraph_format.space_after = Pt(2)
    add_hyperlink(p, url, linktext, size=size)
    if after:
        r = p.add_run(" " + after); _style_run(r, size=size)

