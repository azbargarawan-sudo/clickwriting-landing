# -*- coding: utf-8 -*-
import re, json
def items(path):
    s = open(path, encoding='utf-8').read()
    out=[]
    for m in re.finditer(r"\{ t: '(\w+)', text: '((?:[^'\\]|\\.)*)' \}", s):
        out.append((m.group(1), m.group(2).replace("\\'","'")))
    return out
def norm(t):
    t=re.sub(r'\*\*','',t); t=re.sub(r'[.,;:!?…"\'׳״()\[\]]',' ',t)
    return re.sub(r'\s+',' ',t).strip()
tr=[(re.match(r'\*\*([^*:]+):\*\*\s*(.*)',t).group(1).strip() if re.match(r'\*\*([^*:]+):\*\*',t) else None,
     norm(re.sub(r'^\*\*[^*:]+:\*\*\s*','',t))) for k,t in items('content_transcript.js')]
tr=[(a,b) for a,b in tr if a]
def where(q):
    qn=norm(q); w=qn.split()
    hits={sp for sp,sq in tr if qn and qn in sq}
    if hits: return ('EXACT', sorted(hits))
    for n in (7,5,4):
        probe=' '.join(w[:n])
        hits={sp for sp,sq in tr if probe in sq}
        if hits: return (f'PARTIAL{n}', sorted(hits))
    return ('MISSING', [])

