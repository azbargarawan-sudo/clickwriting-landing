const HEB = "David";
const LAT = "Times New Roman";
const LATIN_RE = /[A-Za-zÀ-ɏ][A-Za-zÀ-ɏ0-9 .,&;:'’\-=<>%/]*[A-Za-zÀ-ɏ0-9%]/g;

// Split a Hebrew string into runs: Hebrew (rtl, David) / Latin (ltr, Times), with [[...]] = highlighted placeholder
function runs(text, opts = {}) {
  const out = [];
  const parts = text.split(/(\[\[.*?\]\])/);
  for (const part of parts) {
    if (!part) continue;
    let hl = false, s = part;
    if (part.startsWith("[[") && part.endsWith("]]")) { hl = true; s = part.slice(2, -2); }
    let last = 0;
    for (const m of s.matchAll(LATIN_RE)) {
      if (m.index > last) out.push(hebRun(s.slice(last, m.index), hl, opts));
      out.push(latRun(m[0], hl, opts));
      last = m.index + m[0].length;
    }
    if (last < s.length) out.push(hebRun(s.slice(last), hl, opts));
  }
  return out;
}
function hebRun(t, hl, o) {
  return new TextRun({ text: t, font: HEB, rightToLeft: true, size: o.size || 24, bold: o.bold, italics: o.italics, highlight: hl ? "yellow" : undefined });
}
function latRun(t, hl, o) {
  return new TextRun({ text: t, font: LAT, size: o.size || 24, bold: o.bold, italics: o.italics, highlight: hl ? "yellow" : undefined });
}

// Hebrew paragraph
function P(text, o = {}) {
  return new Paragraph({
    bidirectional: true,
    alignment: o.align || AlignmentType.BOTH,
    spacing: { line: 480, after: 0 },
    indent: o.noIndent ? undefined : { firstLine: o.firstLine === undefined ? 567 : o.firstLine },
    children: runs(text, o),
  });
}
// English paragraph
function PL(text, o = {}) {
  const parts = text.split(/(\[\[.*?\]\])/).filter(Boolean).map(p => {
    const hl = p.startsWith("[[");
    const s = hl ? p.slice(2, -2) : p;
    return new TextRun({ text: s, font: LAT, size: 24, bold: o.bold, italics: o.italics, highlight: hl ? "yellow" : undefined });
  });
  return new Paragraph({ alignment: o.align || AlignmentType.LEFT, spacing: { line: 480, after: 0 }, indent: o.indent, children: parts });
}
function H1(text, o = {}) {
  return new Paragraph({ heading: HeadingLevel.HEADING_1, bidirectional: true, alignment: AlignmentType.RIGHT, pageBreakBefore: o.noBreak ? false : true, spacing: { line: 480, before: 0, after: 240 }, children: [hebRun(text, false, { size: 32, bold: true })] });
}
function H2(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_2, bidirectional: true, alignment: AlignmentType.RIGHT, spacing: { line: 480, before: 240, after: 120 }, children: [hebRun(text, false, { size: 28, bold: true })] });
}
function H3(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_3, bidirectional: true, alignment: AlignmentType.RIGHT, spacing: { line: 480, before: 120, after: 60 }, children: [hebRun(text, false, { size: 24, bold: true })] });
}
function Empty() { return new Paragraph({ children: [new TextRun("")] }); }

// Hebrew reference entry: hanging indent on the right (start side in a bidi paragraph)
function RefHe(text) {
  return new Paragraph({ bidirectional: true, alignment: AlignmentType.RIGHT, spacing: { line: 480, after: 0 }, indent: { start: 709, hanging: 709 }, children: runs(text) });
}
// English reference entry: left aligned, hanging indent, italic segments marked with *...*
function RefEn(text) {
  const children = [];
  text.split(/(\*.*?\*)/).filter(Boolean).forEach(p => {
    const it = p.startsWith("*");
    children.push(new TextRun({ text: it ? p.slice(1, -1) : p, font: LAT, size: 24, italics: it }));
  });
  return new Paragraph({ alignment: AlignmentType.LEFT, spacing: { line: 480, after: 0 }, indent: { left: 709, hanging: 709 }, children });
}

// Table (RTL). rows: array of arrays of strings. widths in DXA, must sum to total.
function T(headers, rows, widths) {
  const border = { style: BorderStyle.SINGLE, size: 4, color: "000000" };
  const none = { style: BorderStyle.NONE, size: 0, color: "FFFFFF" };
  const cell = (t, i, isHead) => new TableCell({
    width: { size: widths[i], type: WidthType.DXA },
    borders: { top: isHead ? border : none, bottom: isHead ? border : none, left: none, right: none },
    shading: isHead ? { type: ShadingType.CLEAR, fill: "EDEDED", color: "auto" } : undefined,
    margins: { top: 60, bottom: 60, left: 80, right: 80 },
    children: [new Paragraph({ bidirectional: true, alignment: AlignmentType.CENTER, spacing: { line: 276, after: 0 }, children: runs(t, { bold: isHead, size: 22 }) })],
  });
  const lastBorder = (cells) => cells;
  const trs = [new TableRow({ tableHeader: true, children: headers.map((h, i) => cell(h, i, true)) })];
  rows.forEach((r, ri) => {
    const isLast = ri === rows.length - 1;
    trs.push(new TableRow({
      children: r.map((c, i) => {
        const tc = cell(c, i, false);
        return tc;
      }),
    }));
  });
  return new Table({
    visuallyRightToLeft: true,
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    columnWidths: widths,
    borders: { top: border, bottom: border, left: none, right: none, insideHorizontal: none, insideVertical: none },
    rows: trs,
  });
}
function Caption(text) {
  return new Paragraph({ bidirectional: true, alignment: AlignmentType.RIGHT, spacing: { line: 360, before: 240, after: 120 }, keepNext: true, children: runs(text, { bold: true }) });
}
function Note(text) {
  return new Paragraph({ bidirectional: true, alignment: AlignmentType.RIGHT, spacing: { line: 276, after: 240 }, children: runs(text, { size: 20 }) });
}

